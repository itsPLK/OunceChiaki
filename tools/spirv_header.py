#!/usr/bin/env python3
"""Compiles the video shaders to SPIR-V and writes them as a C++ header.

Usage: spirv_header.py <shader dir> <output header>
Emits uint32_t arrays for the video graphics, motion estimation, EASU and RCAS pipelines.
"""
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, output = Path(sys.argv[1]), Path(sys.argv[2])
    compiler = shutil.which("glslangValidator") or sys.exit("glslangValidator is required")
    validator = shutil.which("spirv-val")
    header = "#pragma once\n// Generated by tools/spirv_header.py.\n#include <cstdint>\n"
    with tempfile.TemporaryDirectory() as work:
        for name, file, defines in (("vert", "video.vert", []), ("frag", "video.frag", []),
                                    ("texel_frag", "video.frag", ["-DTEXEL_BUFFER_SAMPLING=1"]),
                                    ("predict_frag", "video.frag", ["-DPREDICT=1"]),
                                    ("midpoint_frag", "video.frag", ["-DINTERPOLATE=1"]),
                                    ("flow", "video.comp", []),
                                    ("easu", "easu.comp", []),
                                    ("easu_scratch", "easu.comp", ["-DTO_SCRATCH=1"]),
                                    ("rcas", "rcas.comp", [])):
            binary = Path(work) / f"{name}.spv"
            subprocess.run([compiler, "-V", "--target-env", "vulkan1.1", *defines,
                            str(source / file), "-o", str(binary)],
                           check=True, stdout=subprocess.DEVNULL)
            if validator:
                subprocess.run([validator, "--target-env", "vulkan1.1", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            header += f"alignas(4) static constexpr uint32_t video_{name}[] = {{\n"
            for i in range(0, len(words), 8):
                header += ",".join(hex(w) for w in words[i:i + 8]) + ",\n"
            header += "};\n"
    if not output.exists() or output.read_text() != header:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(header)


if __name__ == "__main__":
    main()
